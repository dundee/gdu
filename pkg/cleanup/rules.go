// Package cleanup classifies scanned items into cleanup categories, such as
// build artifacts, package caches or downloaded models, so a frontend can draw
// attention to space that is likely regenerable. It never deletes anything.
package cleanup

import (
	"errors"
	"fmt"
	"path/filepath"
	"strings"
)

// Category groups cleanup candidates by what they are.
type Category string

// Known categories.
const (
	BuildArtifact Category = "build-artifact"
	PackageCache  Category = "package-cache"
	AppCache      Category = "app-cache"
	Toolchain     Category = "toolchain"
	MLModel       Category = "ml-model"
	Installer     Category = "installer"
	GitIgnored    Category = "git-ignored"
)

// Confidence tells how safe removing a candidate is.
type Confidence string

// Known confidence levels.
const (
	// Safe candidates are regenerated by their tool on demand.
	Safe Confidence = "safe"
	// Review candidates are probably unneeded but may hold the only copy of
	// something, or need a dedicated tool to be removed cleanly.
	Review Confidence = "review"
)

// CategoryInfo describes a category for display.
type CategoryInfo struct {
	ID    Category `json:"id"`
	Label string   `json:"label"`
}

// Categories lists all categories in display order.
var Categories = []CategoryInfo{
	{ID: BuildArtifact, Label: "Build artifacts"},
	{ID: PackageCache, Label: "Package caches"},
	{ID: AppCache, Label: "App caches"},
	{ID: Toolchain, Label: "SDKs & toolchains"},
	{ID: MLModel, Label: "ML models"},
	{ID: Installer, Label: "Installers & archives"},
	{ID: GitIgnored, Label: "Git-ignored"},
}

// Rule matches items of one category. Exactly one of Dir, File and Path is
// set. A directory matched by a rule is a unit: its descendants are not
// classified on their own.
type Rule struct {
	Category   Category   `yaml:"category"`
	Confidence Confidence `yaml:"confidence"`
	// Dir is a glob matched against the base name of directories.
	Dir string `yaml:"dir"`
	// File is a glob matched against the base name of files.
	File string `yaml:"file"`
	// Path is a glob matched against the absolute path of any item; a
	// leading "~/" stands for the home directory.
	Path string `yaml:"path"`
	// Under restricts the rule to items below this directory ("~/" expands).
	Under string `yaml:"under"`
	// Markers, when set, require at least one sibling with one of these names,
	// e.g. node_modules only counts as a build artifact next to package.json.
	Markers []string `yaml:"markers"`
	// Hint is shown to the user next to the candidate.
	Hint string `yaml:"hint"`
}

var errNoMatcher = errors.New("exactly one of dir, file or path must be set")

func (r *Rule) validate() error {
	if !knownCategory(r.Category) {
		return fmt.Errorf("unknown category %q", r.Category)
	}
	if r.Confidence != Safe && r.Confidence != Review {
		return fmt.Errorf("unknown confidence %q", r.Confidence)
	}
	set := 0
	for _, pattern := range []string{r.Dir, r.File, r.Path} {
		if pattern == "" {
			continue
		}
		set++
		if _, err := filepath.Match(pattern, ""); err != nil {
			return fmt.Errorf("pattern %q: %w", pattern, err)
		}
	}
	if set != 1 {
		return errNoMatcher
	}
	return nil
}

func knownCategory(c Category) bool {
	for _, info := range Categories {
		if info.ID == c {
			return true
		}
	}
	return false
}

// expandHome replaces a leading "~/" (or a bare "~") with home.
func expandHome(path, home string) string {
	if path == "~" {
		return home
	}
	if strings.HasPrefix(path, "~/") {
		return filepath.Join(home, path[2:])
	}
	return path
}

